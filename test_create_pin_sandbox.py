"""
One-time sandbox test — separate from your real pipeline.

Trial-access apps can't create Pins on the normal API at all.
Sandbox uses its own domain AND its own token (the one you just
generated by selecting "Sandbox" in the Generate Access Tokens screen).

Paste that token below and run this once just to see the create-pin
flow actually work. This has nothing to do with your real automation —
once you're on Standard access, you go back to using pinterest_pins.py
against the normal api.pinterest.com domain and never touch this again.
"""
import requests

SANDBOX_TOKEN = "PASTE_YOUR_SANDBOX_TOKEN_HERE"
API_BASE = "https://api-sandbox.pinterest.com/v5"

headers = {
    "Authorization": f"Bearer {SANDBOX_TOKEN}",
    "Content-Type": "application/json",
}

payload = {
    "board_id": "905786612495800306",  # your real 90's Nostalgia board
    "title": "Test Pin - Nostalgic Word Search Book",
    "description": "Just testing the API integration, ignore this one.",
    "link": "https://wittynostalgia.com",
    "media_source": {
        "source_type": "image_url",
        "url": "https://wittynostalgia.com/cdn/shop/files/witty-nostalgia-hero-banner.png",
    },
}

resp = requests.post(f"{API_BASE}/pins", headers=headers, json=payload)
print(resp.status_code)
print(resp.json())
